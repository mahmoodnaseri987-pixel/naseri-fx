export type PhaseInfo =
  | { status: "playing"; round: number; phase: "answer" | "reveal"; endsInMs: number }
  | { status: "finished" };

/** بر اساس زمان شروع مسابقه، وضعیت فعلی را محاسبه می‌کند — بدون هیچ وابستگی به درخواست‌ها */
export function computePhase(startedAtMs: number, now: number): PhaseInfo {
  const elapsed = now - startedAtMs;
  if (elapsed < 0) {
    return { status: "playing", round: 0, phase: "answer", endsInMs: ANSWER_MS + Math.abs(elapsed) };
  }
  const round = Math.floor(elapsed / PERIOD_MS);
  if (round >= ROUND_COUNT) return { status: "finished" };
  const offset = elapsed % PERIOD_MS;
  if (offset < ANSWER_MS) {
    return { status: "playing", round, phase: "answer", endsInMs: ANSWER_MS - offset };
  }
  return { status: "playing", round, phase: "reveal", endsInMs: PERIOD_MS - offset };
}

/** امتیاز یک پاسخ درست بر اساس زمان باقی‌مانده — پاسخ سریع‌تر = امتیاز بیشتر */
export function scoreFor(remainingMs: number): number {
  const ratio = Math.max(0, Math.min(1, remainingMs / ANSWER_MS));
  return 60 + Math.round(60 * ratio);
}

function shuffle<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * انتخاب سؤال‌های یک مسابقه — بدون هیچ تکرار و با پوشش همه دسته‌ها:
 * هر دسته درهم می‌شود و سؤال‌ها به‌صورت رفت‌وبرگشتی از دسته‌های مختلف
 * برمی‌خورند؛ با ۱۰ دسته، هر مسابقه از همه دسته‌ها (هر کدام یک سؤال) دارد.
 */
export function pickQuestions(count: number = ROUND_COUNT): ArenaQuestion[] {
  const byCat = new Map<ArenaCategory, ArenaQuestion[]>();
  for (const q of QUESTION_POOL) {
    const arr = byCat.get(q.c) ?? [];
    arr.push(q);
    byCat.set(q.c, arr);
  }
  for (const arr of byCat.values()) shuffle(arr);
  const cats = shuffle([...byCat.keys()]);
  const out: ArenaQuestion[] = [];
  while (out.length < count) {
    let progressed = false;
    for (const c of cats) {
      const arr = byCat.get(c)!;
      if (arr.length > 0) {
        out.push(arr.pop()!);
        progressed = true;
        if (out.length === count) break;
      }
    }
    if (!progressed) break; // بانک تمام شد
  }
  return out;
}

/** کد اتاق ۵ حرفی — بدون حروف و اعداد گیج‌کننده (۰/اُ/۱/آی) */
const CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";

export function generateRoomCode(): string {
  let code = "";
  for (let i = 0; i < 5; i++) {
    code += CODE_ALPHABET[Math.floor(Math.random() * CODE_ALPHABET.length)];
  }
  return code;
}
