/* ================================================================
   «ضرب‌المثل‌چین» — کاتالوگ کارت‌های کلمه‌ای متحرک
   هر کلمهٔ مهم یک کارت با انیمیشن حلقه‌ای CSS دارد (سبک، یکدست،
   بدون حق کپی‌رایت — به‌جای GIF/WebP آماده). فقط کلید کارت در
   state می‌آید؛ کارت‌ها سمت کلاینت از همین کاتالوگ رندر می‌شوند.
   انواع:
     name  — اسم/فعل، هستهٔ بازی
     mod   — صفت/رنگ/اندازه/حالت/نفی؛ روی کارت دیگر سوار می‌شود
     link  — ربط‌ها (از، به، در، با، ...) با نماد جهت
     joker — کارت پرسشگر؛ شکل پایه (دایره/مربع/خط) جای کلمهٔ بی‌کارت
   m = کلاس انیمیشن حلقه‌ای (pc-* در کلاینت)
   ================================================================ */

export type PcCardType = "name" | "mod" | "link" | "joker";

export type PcCardDef = {
  k: string; // کلید یکتا — پیشوند نوع + واژه
  w: string; // واژهٔ روی کارت
  e?: string; // ایموجی (اختیاری — کارت‌های انتزاعی فقط واژه‌اند)
  m: string; // انیمیشن حلقه‌ای
  t: PcCardType;
};

const N = (k: string, w: string, e: string, m: string): PcCardDef => ({ k: `w.${k}`, w, e, m, t: "name" });
const N0 = (k: string, w: string, m: string): PcCardDef => ({ k: `w.${k}`, w, m, t: "name" });
const M = (k: string, w: string, e: string, m = "none"): PcCardDef => ({ k: `m.${k}`, w, e, m, t: "mod" });
const L = (k: string, e: string): PcCardDef => ({ k: `l.${k}`, w: k, e, m: "none", t: "link" });

