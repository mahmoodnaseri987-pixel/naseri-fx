async function main() {
  for (const s of SONGS) {
    const data = {
      title: s.title,
      artist: "تست داخلی",
      clipStart: 2, // شروع کلیپ از ثانیهٔ ۲
      answerLine: s.answerLine,
      contextLines: JSON.stringify(s.contextLines),
      extraLines: JSON.stringify(s.extraLines),
      active: true,
    };
    await db.sherSong.upsert({
      where: { filename: s.filename },
      update: data,
      create: { filename: s.filename, ...data },
    });
    console.log(`sher_seed: ${s.filename} ذخیره شد.`);
  }
  await db.$disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
